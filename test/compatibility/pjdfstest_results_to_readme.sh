#!/usr/bin/env bash
# Parse pjd/pjdfstest prove output and output compatibility results
# This script is called by the CI workflow to process test results
# Output goes to stdout for redirection to a file

set -o errexit
set -o nounset
set -o pipefail

SCRIPT_DIR="$(dirname "${BASH_SOURCE[0]}")"
OUTPUT_LOG="${1:-${SCRIPT_DIR}/pjdfstest-logs/test_output.log}"

# Check if output log exists
if [ ! -f "$OUTPUT_LOG" ]; then
    echo "No pjdfstest output log found at $OUTPUT_LOG"
    echo "pass_count=0" >> "${GITHUB_OUTPUT:-/dev/null}"
    echo "fail_count=0" >> "${GITHUB_OUTPUT:-/dev/null}"
    exit 0
fi

echo "# S3D pjd/pjdfstest Compatibility Test Results"
echo ""
echo "This file is auto-generated by the CI workflow from pjd/pjdfstest results"
echo "run against an s3fs-fuse mount backed by s3d."
echo ""

# Parse all test results using Python for consistency
python3 << 'PYTHON_SCRIPT' - "$OUTPUT_LOG"
import sys
import re

output_log = sys.argv[1]

with open(output_log, errors="replace") as f:
    lines = f.read().splitlines()

# Per test-script results, keyed by path relative to the pjdfstest tests dir
results = {}  # name -> dict(total, failed, failed_tests)
order = []

file_re = re.compile(r'^\S*/tests/(\S+\.t)\s*\.*\s*(.*)$')
failed_re = re.compile(r'^Failed (\d+)/(\d+) subtests')
summary_file_re = re.compile(
    r'^\S*/tests/(\S+\.t)\s+\(Wstat: \d+(?: \(.*?\))? Tests: (\d+) Failed: (\d+)\)')

current = None
in_summary = False
summary_current = None
collecting = None  # 'failed' when collecting failed test numbers

for line in lines:
    if line.startswith('Test Summary Report'):
        in_summary = True
        continue

    if not in_summary:
        m = file_re.match(line)
        if m:
            name, status = m.group(1), m.group(2).strip()
            current = name
            if name not in results:
                order.append(name)
            results[name] = {'status': status, 'total': None,
                             'failed': 0, 'failed_tests': ''}
            if status:
                current = None
            continue
        m = failed_re.match(line.strip())
        if m and current is not None:
            results[current]['status'] = line.strip()
            current = None
        continue

    # Test Summary Report section
    m = summary_file_re.match(line)
    if m:
        name, total, failed = m.group(1), int(m.group(2)), int(m.group(3))
        summary_current = name
        collecting = None
        if name in results:
            results[name]['total'] = total
            results[name]['failed'] = failed
        continue
    stripped = line.strip()
    if summary_current is not None and summary_current in results:
        if stripped.startswith('Failed test'):
            collecting = 'failed'
            nums = stripped.split(':', 1)[1].strip()
            results[summary_current]['failed_tests'] += nums
            continue
        if collecting == 'failed' and re.match(r'^[\d, -]+$', stripped) and stripped:
            results[summary_current]['failed_tests'] += ' ' + stripped
            continue
    collecting = None

# Overall summary from the final "Files=..., Tests=..." line
files_total = tests_total = 0
for line in lines:
    m = re.match(r'^Files=(\d+), Tests=(\d+)', line)
    if m:
        files_total, tests_total = int(m.group(1)), int(m.group(2))

passed_files = [n for n in order if results[n]['status'] == 'ok'
                or results[n]['status'].startswith('ok')]
skipped_files = [n for n in order if results[n]['status'].startswith('skipped')]
failed_files = [n for n in order
                if n not in passed_files and n not in skipped_files]

tests_failed = sum(results[n]['failed'] for n in order)
tests_passed = tests_total - tests_failed

print("## Summary")
print("")
print("| Status | Count |")
print("|--------|-------|")
print(f"| ✅ PASS | {tests_passed} |")
print(f"| ❌ FAIL | {tests_failed} |")
print(f"| 📊 TOTAL | {tests_total} |")
print("")
print(f"Test scripts: {len(passed_files)} passed, {len(failed_files)} failed, "
      f"{len(skipped_files)} skipped, {files_total} total.")
print("")

print("## Detailed Results")
print("")

print("### ✅ Passed Test Scripts")
print("")
print("| Test Script |")
print("|-------------|")
if passed_files:
    for name in sorted(passed_files):
        print(f"| `{name}` |")
else:
    print("| (none) |")
print("")

print("### ❌ Failed Test Scripts")
print("")
print("| Test Script | Result | Failed Subtests |")
print("|-------------|--------|-----------------|")
if failed_files:
    for name in sorted(failed_files):
        r = results[name]
        status = r['status'].replace('|', '\\|') or 'unknown'
        failed_tests = re.sub(r'\s+', ' ', r['failed_tests']).strip()
        print(f"| `{name}` | {status} | {failed_tests} |")
else:
    print("| (none) | | |")
print("")

print("### ⏭️ Skipped Test Scripts")
print("")
print("| Test Script | Reason |")
print("|-------------|--------|")
if skipped_files:
    for name in sorted(skipped_files):
        status = results[name]['status'].replace('|', '\\|')
        print(f"| `{name}` | {status} |")
else:
    print("| (none) | |")

# Output to GitHub Actions output variables if available
import os
gh_output = os.environ.get('GITHUB_OUTPUT')
if gh_output:
    with open(gh_output, 'a') as f:
        f.write(f"pass_count={tests_passed}\n")
        f.write(f"fail_count={tests_failed}\n")
PYTHON_SCRIPT

echo ""
